import {existsSync,readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
for (const file of ['proto/identity.proto','proto/catalog.proto','proto/playback.proto','proto/analytics.proto','proto/notifications.proto','docker-compose.local.yml','videos/sample.mp4']) assert.ok(existsSync(file),`Falta ${file}`);
const compose=readFileSync('docker-compose.local.yml','utf8');
for(const service of ['identity:','catalog:','playback:','analytics:','notifications:','gateway:','frontend:']) assert.match(compose,new RegExp('\\n  '+service));
const gateway=readFileSync('gateway/src/main.ts','utf8');
assert.match(gateway,/httpOnly:true,secure:true,sameSite:'strict'/);
assert.match(gateway,/clients\.playback\.StreamVideo/);
const grpc=readFileSync('gateway/src/grpc.ts','utf8');
for(const name of ['IDENTITY_GRPC_ADDRESS','CATALOG_GRPC_ADDRESS','PLAYBACK_GRPC_ADDRESS','ANALYTICS_GRPC_ADDRESS','NOTIFICATIONS_GRPC_ADDRESS']) assert.match(grpc,new RegExp(`process\\.env\\.${name}`));
assert.match(grpc,/GRPC_TIMEOUT_MS/);
assert.match(grpc,/deadline:grpcDeadline\(\)/);
assert.match(gateway,/GatewayTimeoutException/);
for (const grpcCode of [3,16,6,7,5,4,14]) assert.match(gateway,new RegExp(`case ${grpcCode}:`));
assert.match(gateway,/StreamVideo\([^\n]+deadline:grpcDeadline\(\)/);
const identity=readFileSync('services/identity/src/main.ts','utf8');
assert.match(identity,/GrpcStatus\.INVALID_ARGUMENT/);
assert.match(identity,/GrpcStatus\.UNAUTHENTICATED/);
assert.match(identity,/GrpcStatus\.ALREADY_EXISTS/);
assert.match(identity,/JWT_EXPIRES_IN \|\| '60m'/);
assert.ok(existsSync('services/playback/gen/catalog.pb.go'),'Falta el contrato Go generado de catálogo');
assert.ok(existsSync('services/playback/gen/playback.pb.go'),'Falta el contrato Go generado de reproducción');
const playback=readFileSync('services/playback/cmd/main.go','utf8');
assert.match(playback,/CATALOG_GRPC_ADDRESS/);
assert.match(playback,/PLAYBACK_GRPC_BIND/);
assert.match(compose,/mongosh --quiet/);
assert.match(compose,/redis-cli/);
console.log('Contratos, topología y cookie segura verificados.');
